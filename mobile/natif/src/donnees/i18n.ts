const DICTIONNAIRES: Record<Langue, Record<CleTexte, string>> = { fr, en, es };

export type Traduire = (cle: CleTexte, valeurs?: Record<string, string | number>) => string;

export function traducteur(langue: Langue): Traduire {
  const table = DICTIONNAIRES[langue] || fr;
  return (cle, valeurs) => {
    const brut = table[cle] ?? fr[cle] ?? cle;
    return valeurs ? brut.replace(/\{(\w+)\}/g, (_, nom) => (valeurs[nom] !== undefined ? String(valeurs[nom]) : `{${nom}}`)) : brut;
  };
}

