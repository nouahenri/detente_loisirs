const date = (iso?: string) => new Date(iso || Date.now());
export const dateCourte = (iso: string | undefined, l: Langue) => {
  const d = date(iso);
  return l === 'en' ? `${MOIS.en[d.getMonth()]} ${d.getDate()}, ${d.getFullYear()}` : `${d.getDate()} ${MOIS[l][d.getMonth()]} ${d.getFullYear()}`;
};
export const dateLongue = (iso: string | undefined, l: Langue) => {
  const d = date(iso);
  return l === 'en' ? `${MOIS_LONGS.en[d.getMonth()]} ${d.getDate()}, ${d.getFullYear()}` : `${d.getDate()} ${l === 'es' ? 'de ' : ''}${MOIS_LONGS[l][d.getMonth()]}${l === 'es' ? ' de' : ''} ${d.getFullYear()}`;
};
export const dateJour = (isoJour: string, l: Langue) => {
  const d = new Date(`${isoJour}T12:00:00`);
  if (Number.isNaN(d.getTime())) return '—';
  return l === 'en' ? `${JOURS.en[d.getDay()]}, ${MOIS.en[d.getMonth()]} ${d.getDate()}` : `${JOURS[l][d.getDay()]} ${d.getDate()} ${MOIS[l][d.getMonth()]}`;
};
export const dateHeure = (iso: string, l: Langue) => {
  const d = date(iso);
  return `${dateCourte(iso, l).replace(/ \d{4}$|, \d{4}$/, '')} · ${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
};
export const dateJourMois = (iso: string, l: Langue) => {
  const d = date(iso);
  return l === 'en' ? `${MOIS_LONGS.en[d.getMonth()]} ${d.getDate()}` : `${d.getDate()} ${l === 'es' ? 'de ' : ''}${MOIS_LONGS[l][d.getMonth()]}`;
};
